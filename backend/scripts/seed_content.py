# ruff: noqa: E501
"""Editorial seed content: long interactive articles and quality tasks.

The article documents follow ``docs/interactive-articles-contract.md`` (schema
version 2) and use every block type supported by the renderer: rich text,
formulas, an interactive graph, choice and numeric exercises, step-by-step
solutions, hints, callouts, images and dividers.

Content lives in Python so the seed script stays readable and LaTeX escaping is
explicit. Block ids of exercises and headings are stable: exercise ids key the
per-user progress table, and heading ids are used by the table of contents.
"""

from __future__ import annotations

from typing import Any

# --- inline nodes -------------------------------------------------------------


def t(value: str) -> dict[str, Any]:
    return {"type": "text", "text": value}


def m(tex: str) -> dict[str, Any]:
    return {"type": "math", "tex": tex}


def strong(*children: dict[str, Any]) -> dict[str, Any]:
    return {"type": "strong", "children": list(children)}


def em(*children: dict[str, Any]) -> dict[str, Any]:
    return {"type": "em", "children": list(children)}


def code(value: str) -> dict[str, Any]:
    return {"type": "code", "text": value}


def link(href: str, *children: dict[str, Any]) -> dict[str, Any]:
    return {"type": "link", "href": href, "children": list(children)}


def br() -> dict[str, Any]:
    return {"type": "br"}


# --- block builder ------------------------------------------------------------


class ArticleBuilder:
    """Small helper that keeps block ids unique inside one document."""

    def __init__(self, prefix: str) -> None:
        self.prefix = prefix
        self.blocks: list[dict[str, Any]] = []
        self._counter = 0

    def _id(self, block_id: str | None) -> str:
        if block_id is not None:
            return block_id
        self._counter += 1
        return f"{self.prefix}-{self._counter}"

    def p(self, *children: dict[str, Any], id: str | None = None) -> None:
        self.blocks.append(
            {
                "id": self._id(id),
                "type": "rich_text",
                "data": {"kind": "paragraph", "children": list(children)},
            }
        )

    def h(self, block_id: str, *children: dict[str, Any], level: int = 2) -> None:
        self.blocks.append(
            {
                "id": block_id,
                "type": "rich_text",
                "data": {"kind": "heading", "level": level, "children": list(children)},
            }
        )

    def items_list(
        self,
        items: list[list[dict[str, Any]]],
        *,
        ordered: bool = False,
        id: str | None = None,
    ) -> None:
        self.blocks.append(
            {
                "id": self._id(id),
                "type": "rich_text",
                "data": {"kind": "list", "ordered": ordered, "items": items},
            }
        )

    def math(
        self,
        tex: str,
        *,
        display: bool = True,
        caption: str | None = None,
        id: str | None = None,
    ) -> None:
        data: dict[str, Any] = {"tex": tex, "display": display}
        if caption is not None:
            data["caption"] = caption
        self.blocks.append({"id": self._id(id), "type": "math", "data": data})

    def graph(self, data: dict[str, Any], *, id: str | None = None) -> None:
        self.blocks.append({"id": self._id(id), "type": "interactive_graph", "data": data})

    def choice(
        self,
        block_id: str,
        prompt: list[dict[str, Any]],
        options: list[tuple[str, list[dict[str, Any]]]],
        correct: str,
        explanation: list[dict[str, Any]],
    ) -> None:
        self.blocks.append(
            {
                "id": block_id,
                "type": "single_choice",
                "data": {
                    "prompt": prompt,
                    "options": [{"id": option_id, "label": label} for option_id, label in options],
                    "correct_option_id": correct,
                    "explanation": explanation,
                },
            }
        )

    def numeric(
        self,
        block_id: str,
        prompt: list[dict[str, Any]],
        value: float,
        *,
        tolerance: float = 0.0,
        unit: str = "",
        explanation: list[dict[str, Any]] | None = None,
    ) -> None:
        data: dict[str, Any] = {
            "prompt": prompt,
            "correct_value": value,
            "tolerance": tolerance,
            "unit": unit,
        }
        if explanation is not None:
            data["explanation"] = explanation
        self.blocks.append({"id": block_id, "type": "numeric_input", "data": data})

    def solution(
        self,
        steps: list[tuple[str, list[dict[str, Any]], str | None]],
        *,
        id: str | None = None,
    ) -> None:
        rendered: list[dict[str, Any]] = []
        for step_id, note, tex in steps:
            step: dict[str, Any] = {"id": step_id, "note": note}
            if tex is not None:
                step["math"] = {"tex": tex, "display": True}
            rendered.append(step)
        self.blocks.append(
            {"id": self._id(id), "type": "step_solution", "data": {"steps": rendered}}
        )

    def hint(
        self,
        body: list[dict[str, Any]],
        *,
        title: str = "Подсказка",
        id: str | None = None,
    ) -> None:
        self.blocks.append(
            {"id": self._id(id), "type": "hint", "data": {"title": title, "body": body}}
        )

    def callout(
        self,
        kind: str,
        title: str,
        body: list[dict[str, Any]],
        *,
        id: str | None = None,
    ) -> None:
        self.blocks.append(
            {
                "id": self._id(id),
                "type": "callout",
                "data": {"kind": kind, "title": title, "body": body},
            }
        )

    def image(
        self,
        src: str,
        alt: str,
        caption: str | None = None,
        *,
        width: int | None = None,
        height: int | None = None,
        id: str | None = None,
    ) -> None:
        data: dict[str, Any] = {"src": src, "alt": alt}
        if caption is not None:
            data["caption"] = caption
        if width is not None:
            data["width"] = width
        if height is not None:
            data["height"] = height
        self.blocks.append({"id": self._id(id), "type": "image", "data": data})

    def divider(self, *, variant: str = "spaced", id: str | None = None) -> None:
        self.blocks.append({"id": self._id(id), "type": "divider", "data": {"variant": variant}})

    def build(self) -> dict[str, Any]:
        return {"version": 2, "blocks": self.blocks}


