    a.math(r"(a^m)^n=a^{mn},\qquad (ab)^n=a^n b^n,\qquad \left(\frac{a}{b}\right)^n=\frac{a^n}{b^n}")
    a.math(r"a^{-n}=\frac{1}{a^n},\qquad a^0=1\ (a\neq 0)", caption="Отрицательный и нулевой показатель")
    a.p(
        t(
            "Все эти свойства работают при допустимых основаниях: делить на ноль нельзя, а для дробных показателей нужны дополнительные ограничения."
        )
    )

    a.h("powers-korni", t("Свойства квадратных корней"))
    a.math(r"\sqrt{ab}=\sqrt{a}\sqrt{b}\ (a\ge 0,\ b\ge 0)", caption="Корень произведения")
    a.math(r"\sqrt{\frac{a}{b}}=\frac{\sqrt{a}}{\sqrt{b}}\ (a\ge 0,\ b>0)", caption="Корень частного")
    a.math(r"\sqrt{a^2}=|a|", caption="Важное ограничение")
    a.p(
        t(
            "Последнее свойство часто записывают как «корень из квадрата равен числу», но это верно только для неотрицательного числа. Для отрицательного a результат равен −a."
        )
    )

    a.h("powers-primer1", t("Пример 1: степени"))
    a.p(t("Вычислите "), m(r"2^5\cdot 2^{-3}"), t("."))
    a.solution(
        [
            ("s1", [t("Складываем показатели при одинаковых основаниях.")], r"2^5\cdot 2^{-3}=2^{5-3}=2^2"),
            ("s2", [t("Считаем.")], r"2^2=4"),
        ],
        id="powers-solution-1",
    )

    a.h("powers-primer2", t("Пример 2: корень"))
    a.p(t("Упростите "), m(r"\sqrt{50}"), t("."))
    a.solution(
        [
            ("s1", [t("Раскладываем 50 на множители с полным квадратом.")], r"\sqrt{50}=\sqrt{25\cdot 2}"),
            ("s2", [t("Выносим корень из 25.")], r"5\sqrt{2}"),
        ],
        id="powers-solution-2",
    )

    a.h("powers-primer3", t("Пример 3: разность квадратов под корнем"))
    a.p(t("Вычислите "), m(r"(\sqrt{7}-2)(\sqrt{7}+2)"), t("."))
